use std::path::PathBuf;
use std::{env, fs};

fn main() {
    editor_limits();
    tauri_build::build()
}

/// The Editor's import cap (SPEC §6) has ONE definition, shared with the
/// webview: src/editor/limits.json. The webview imports that file; this
/// generates `IMPORT_MAX_SIDE` from it for src/editor/import.rs.
fn editor_limits() {
    let manifest = PathBuf::from(env::var("CARGO_MANIFEST_DIR").unwrap());
    let path = manifest.join("../src/editor/limits.json");
    println!("cargo:rerun-if-changed={}", path.display());
    let text = fs::read_to_string(&path)
        .unwrap_or_else(|e| panic!("cannot read {}: {e}", path.display()));
    let limits: serde_json::Value = serde_json::from_str(&text)
        .unwrap_or_else(|e| panic!("{} is not valid JSON: {e}", path.display()));
    let side = limits["importMaxSide"]
        .as_u64()
        .filter(|&n| n >= 1 && n <= u64::from(u32::MAX))
        .unwrap_or_else(|| panic!("{}: importMaxSide must be a whole number of pixels, 1 or more", path.display()));
    let out = PathBuf::from(env::var("OUT_DIR").unwrap()).join("editor_limits.rs");
    let code = format!(
        "/// Largest side an imported image may have without scaling (SPEC §6),\n\
         /// generated by build.rs from src/editor/limits.json (shared with the webview).\n\
         pub const IMPORT_MAX_SIDE: u32 = {side};\n"
    );
    fs::write(&out, code).unwrap_or_else(|e| panic!("cannot write {}: {e}", out.display()));
}
